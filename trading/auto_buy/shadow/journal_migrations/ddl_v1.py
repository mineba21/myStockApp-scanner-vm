"""자동매수 SHADOW 저널 스키마 v1 DDL (리비전 ab0001 이 배포되면 동결). 이후 스키마 변경은 새 리비전·새 DDL 모듈로 한다.

모든 객체 이름은 ``ab_`` 로 시작한다. 이 SQLite 는 자동매수 SHADOW 전용이며 운영 DB·S01 주문 저널과 다른 파일이다.
- 신호 스냅샷(``ab_signal_snapshots``)·일봉 입력(``ab_bars``)은 INSERT 만 허용한다 (UPDATE·DELETE 트리거로 거부).
- 거래일 입력(``ab_day_inputs``)은 한 번 확정한 결정 스캔·계좌 스냅샷을 바꾸지 않는다 (트리거).
- 가상 계좌 상태는 재계산 run(``ab_runs``) 단위로 분리한다. 일봉 복구로 다시 계산하면 새 run 을 만들고
  이전 run 행은 감사 이력으로 남긴다 (덮어쓰기·삭제 없음).
- 가상 주문·체결·포지션·S01 가상 손절 행은 ``is_virtual = 1`` CHECK 로 실제 체결과 섞이지 않게 한다.
"""

